# =====================================================================
#  Build-Single.ps1
#  Merges the modular src\ files and the main script into one portable
#  file: Scottimizer.Standalone.ps1
# =====================================================================
$ErrorActionPreference = 'Stop'
$root = $PSScriptRoot
if (-not $root) { $root = (Get-Location).Path }

$modules = 'Core.ps1','Tools.ps1','Tweaks.ps1','Audit.ps1','Ui.ps1','Personalize.ps1','Benchmark.ps1','Actions.ps1'
$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine("# ==== Scottimizer 2 - standalone build ($(Get-Date -Format 'yyyy-MM-dd HH:mm')) ====")
[void]$sb.AppendLine("# Generated by Build-Single.ps1 - edit the src\ files, not this one.")
[void]$sb.AppendLine()

foreach ($m in $modules) {
    $p = Join-Path $root ("src\{0}" -f $m)
    if (-not (Test-Path $p)) { throw "Missing module: $p" }
    [void]$sb.AppendLine("# ---------------- $m ----------------")
    [void]$sb.AppendLine((Get-Content -LiteralPath $p -Raw))
    [void]$sb.AppendLine()
}

# Main script without the dot-source lines (modules are inlined above)
$mainLines = Get-Content -LiteralPath (Join-Path $root 'Scottimizer.ps1')
$mainLines = $mainLines | Where-Object { $_ -notmatch '^\s*\.\s*\(Join-Path' }
[void]$sb.AppendLine("# ---------------- Scottimizer.ps1 (main) ----------------")
[void]$sb.AppendLine(($mainLines -join "`r`n"))

$out = Join-Path $root 'Scottimizer.Standalone.ps1'
Set-Content -LiteralPath $out -Value $sb.ToString() -Encoding UTF8
Write-Host "Built: $out"
